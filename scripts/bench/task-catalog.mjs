/**
 * Capstan planner bench — 100 distinct coding tasks.
 * Suites: smoke (~10 cases) ⊆ core (~30) ⊆ full (100 prompts).
 * Model and authentication come from Pi; no provider lock or fallback.
 */

const VERIFY_HINT =
  "Acceptance commands must use only allowlisted prefixes such as `true`, `npm test`, `node --test`, `pytest`, or `python -m pytest`. Never use shell pipes, curl|sh, or rm -rf.";

function t(partial) {
  const suites = partial.suites ?? ["full"];
  if (partial.smoke) suites.unshift("smoke");
  if (partial.core && !suites.includes("core")) suites.splice(suites.includes("smoke") ? 1 : 0, 0, "core");
  // smoke ⊆ core ⊆ full
  const suiteSet = new Set(["full", ...suites]);
  if (suiteSet.has("smoke")) suiteSet.add("core");
  return {
    fixtures: [partial.fixture],
    difficulty: partial.difficulty ?? "medium",
    expectOutcome: partial.expectOutcome ?? "plan",
    adversarial: partial.adversarial ?? null,
    tags: partial.tags ?? [],
    ...partial,
    suites: [...suiteSet],
  };
}

